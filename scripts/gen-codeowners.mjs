#!/usr/bin/env node
/**
 * gen-codeowners.mjs: writes .github/CODEOWNERS from each package's `genesis.owner` (feature
 * `package-owners`), so ownership can split per package or group without a process change.
 *
 *   node scripts/gen-codeowners.mjs           write it
 *   node scripts/gen-codeowners.mjs --check   exit 1 when a package has no owner or the file is stale
 *
 * The first line stays `* <default>`: anything outside a package is the maintainer's.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const DEFAULT_OWNER = "@marktiderman";
const FILE = ".github/CODEOWNERS";

/** The CODEOWNERS text for these packages, and the problems (a package with no owner). */
export function codeowners(packages, defaultOwner = DEFAULT_OWNER) {
  const problems = [];
  const lines = [
    "# Generated by `pnpm gen:codeowners` from each package's genesis.owner. Don't edit by hand.",
    "# Everything outside a package is reviewed by the maintainer.",
    `* ${defaultOwner}`,
    "",
  ];
  for (const p of [...packages].sort((a, b) => a.dir.localeCompare(b.dir))) {
    if (!p.owner) problems.push(`packages/${p.dir}: set "genesis": { "owner": "@handle" } in its package.json`);
    else lines.push(`/packages/${p.dir}/ ${p.owner}`);
  }
  return { text: `${lines.join("\n")}\n`, problems };
}

function readPackages(root) {
  const dir = path.join(root, "packages");
  return readdirSync(dir)
    .filter((d) => existsSync(path.join(dir, d, "package.json")))
    .map((d) => ({ dir: d, owner: JSON.parse(readFileSync(path.join(dir, d, "package.json"), "utf8")).genesis?.owner }));
}

function main(argv) {
  const root = process.cwd();
  const { text, problems } = codeowners(readPackages(root));
  for (const p of problems) console.error(`✗ ${p}`);
  if (problems.length) return 1;
  const file = path.join(root, FILE);
  if (argv.includes("--check")) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      console.error(`✗ ${FILE} is stale. Run \`pnpm gen:codeowners\` and commit the result.`);
      return 1;
    }
    console.log(`✔ ${FILE} matches every package's owner.`);
    return 0;
  }
  writeFileSync(file, text);
  console.log(`wrote ${FILE}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exitCode = main(process.argv.slice(2));
