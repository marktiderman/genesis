#!/usr/bin/env node
/**
 * Writes src/native/emoji-data.ts, the emoji the native picker bundles, from a local copy of
 * emojibase-data (MIT, https://github.com/milesj/emojibase). The picker never fetches: the
 * data ships in the app, so opening it sends nothing anywhere.
 *
 *   npm pack emojibase-data@16.0.3 && tar xzf emojibase-data-16.0.3.tgz
 *   node packages/chat/scripts/build-emoji-data.mjs ./package
 *
 * Kept small: base emoji only (no skin tones), Emoji 15.0 and earlier (every glyph iOS 17 and
 * Android 14 draw), the English label and up to three search tags not already in the label.
 *
 * Each emoji is written as people's keyboards type it: emojibase adds U+FE0F after characters
 * that are emoji already ("👍" + FE0F), and a reaction stored that way would count apart from
 * the same reaction typed or chosen from the quick row. FE0F stays where it matters ("❤️").
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MAX_VERSION = 15;
const MAX_TAGS = 3;
const GROUPS = {
  0: "smileys",
  1: "people",
  3: "nature",
  4: "food",
  5: "travel",
  6: "activities",
  7: "objects",
  8: "symbols",
  9: "flags",
};

const source = process.argv[2];
if (!source) {
  console.error("usage: build-emoji-data.mjs <path to an unpacked emojibase-data package>");
  process.exit(1);
}
const pkg = JSON.parse(readFileSync(join(source, "package.json"), "utf8"));
const data = JSON.parse(readFileSync(join(source, "en", "data.json"), "utf8"));

/** Drops U+FE0F after a character that shows as emoji without it (Emoji_Presentation). */
export function keyboardForm(emoji) {
  return emoji.replace(/(\p{Emoji_Presentation})\uFE0F/gu, "$1");
}

const byGroup = new Map(Object.values(GROUPS).map((id) => [id, []]));
for (const e of data.sort((a, b) => (a.order ?? 0) - (b.order ?? 0))) {
  const group = GROUPS[e.group];
  if (!group || e.version > MAX_VERSION || !e.emoji || !e.label) continue;
  const words = new Set(e.label.toLowerCase().split(/[^a-z0-9]+/));
  const tags = (e.tags ?? []).filter((t) => !words.has(t.toLowerCase())).slice(0, MAX_TAGS);
  if (/[\t\n]/.test(e.label + tags.join(""))) throw new Error(`unexpected separator in ${e.hexcode}`);
  byGroup.get(group).push([keyboardForm(e.emoji), e.label, tags.join(" ")].join("\t"));
}

const out = [
  "/**",
  " * @feat:chat",
  ` * Generated by scripts/build-emoji-data.mjs from emojibase-data ${pkg.version} (MIT,`,
  " * https://github.com/milesj/emojibase). Don't edit: run the script.",
  " *",
  " * Each group is one string, a line per emoji: the emoji, its label and its search tags,",
  " * separated by tabs. Bundled, never fetched.",
  " */",
  `export const EMOJI_DATA_SOURCE = ${JSON.stringify(`emojibase-data@${pkg.version}, Emoji ${MAX_VERSION}.0 and earlier`)};`,
  "",
  "export const EMOJI_GROUP_DATA = {",
  ...[...byGroup].map(([id, lines]) => `  ${id}: ${JSON.stringify(lines.join("\n"))},`),
  "} as const;",
  "",
];
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "native", "emoji-data.ts");
writeFileSync(target, out.join("\n"));
const count = [...byGroup.values()].reduce((n, l) => n + l.length, 0);
console.log(`wrote ${target}: ${count} emoji`);
