// ---------------------------------------------------------------------------
// The one migration a project runs to attach the studio with the `table`
// audit sink (DATA-STUDIO.md "Write safety → Audit before editing").
//
// Print it with `npx genesis-studio-server sql` and save it as a migration.
// It is idempotent, so running it again after an upgrade is safe.
// ---------------------------------------------------------------------------

export interface SetupSqlOptions {
  /** Role the handler acts as. Default `authenticated`. */
  role?: string;
}

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

/** Name of the audit function the handler calls. */
export const AUDIT_FUNCTION = "genesis_studio.record_audit";

/**
 * SQL that installs the tamper-proof audit trail:
 *
 * - schema `genesis_studio`, which no Data API exposes (Supabase exposes
 *   `public` and `graphql_public` unless told otherwise);
 * - table `genesis_studio.audit_log`, on which `anon` and the acting role get
 *   no insert, update or delete, so nobody can forge or erase an entry;
 * - function `genesis_studio.record_audit`, `security definer` with an empty
 *   `search_path`, the ONLY way to add an entry. It takes the actor from the
 *   session's verified claims, never from an argument.
 */
export function studioSetupSql(options: SetupSqlOptions = {}): string {
  const role = quoteIdent(options.role ?? "authenticated");
  return `-- Genesis Data Studio: audit trail for the studio handler.
-- Generated by @marktiderman/genesis-studio-server. Safe to run more than once.

create schema if not exists genesis_studio;
revoke all on schema genesis_studio from public;
grant usage on schema genesis_studio to ${role};

create table if not exists genesis_studio.audit_log (
  id uuid primary key default gen_random_uuid(),
  occurred_at timestamptz not null default clock_timestamp(),
  actor text,
  actor_claims jsonb,
  resource text not null,
  record_key jsonb not null,
  action text not null check (action in ('create', 'update', 'delete')),
  before jsonb,
  after jsonb
);
create index if not exists audit_log_record_idx
  on genesis_studio.audit_log (resource, record_key, occurred_at desc);

-- Nobody writes the log directly, the acting role included. Reading it is a
-- decision for the project (e.g. grant select to a staff role).
revoke all on genesis_studio.audit_log from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on genesis_studio.audit_log from anon';
  end if;
end $$;
revoke all on genesis_studio.audit_log from ${role};

create or replace function genesis_studio.record_audit(
  p_resource text,
  p_record_key jsonb,
  p_action text,
  p_before jsonb,
  p_after jsonb
)
returns table (id uuid, occurred_at timestamptz, actor text)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_claims jsonb := nullif(current_setting('request.jwt.claims', true), '')::jsonb;
  v_actor text := v_claims ->> 'sub';
begin
  if v_actor is null then
    raise exception 'genesis_studio.record_audit: no signed-in user in this session'
      using errcode = 'insufficient_privilege';
  end if;
  return query
    insert into genesis_studio.audit_log
      (actor, actor_claims, resource, record_key, action, before, after)
    values
      (v_actor, v_claims, p_resource, p_record_key, p_action, p_before, p_after)
    returning audit_log.id, audit_log.occurred_at, audit_log.actor;
end;
$fn$;

revoke all on function genesis_studio.record_audit(text, jsonb, text, jsonb, jsonb) from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on function genesis_studio.record_audit(text, jsonb, text, jsonb, jsonb) from anon';
    execute 'revoke all on schema genesis_studio from anon';
  end if;
end $$;
grant execute on function genesis_studio.record_audit(text, jsonb, text, jsonb, jsonb) to ${role};
`;
}
