// ---------------------------------------------------------------------------
// Custom format: Native TypeScript tokens (hex + px numbers)
// ---------------------------------------------------------------------------

const nativeTsFormat = {
  name: "ts/native-tokens",
  format: async ({ dictionary }: FormatFnArguments) => {
    // In DTCG mode, resolved values are on t.$value, not t.value
    function val(t: TransformedToken): unknown {
      return t.$value ?? t.value;
    }

    // Collect token groups
    const colorTokens = dictionary.allTokens.filter(
      (t) => t.$type === "color" && t.path[0] === "color"
    );
    const spacingTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "spacing"
    );
    const radiusTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "radius"
    );
    const fontSizeTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "font" && t.path[1] === "size"
    );
    const lineHeightTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "font" && t.path[1] === "lineHeight"
    );
    const fontWeightTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "font" && t.path[1] === "weight"
    );
    const fontFamilyTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "font" && t.path[1] === "family"
    );

    function pxToNum(v: unknown): number {
      if (typeof v === "number") return v;
      const num = parseFloat(String(v).replace("px", ""));
      if (isNaN(num)) {
        throw new Error(`[style-dictionary] Cannot convert "${v}" to number. Check your DTCG token files.`);
      }
      return num;
    }

    // Build neutral colors
    const neutralObj: Record<string, string> = {};
    for (const t of colorTokens) {
      if (t.path[1] === "neutral") {
        neutralObj[t.path[2]] = val(t) as string;
      }
    }

    // Build semantic colors
    const semanticObj: Record<string, Record<string, string>> = {};
    for (const t of colorTokens) {
      if (t.path[1] === "semantic") {
        const group = t.path[2];
        if (!semanticObj[group]) semanticObj[group] = {};
        semanticObj[group][t.path[3]] = val(t) as string;
      }
    }

    // Build status colors (resolve references)
    const statusObj: Record<string, string> = {};
    for (const t of colorTokens) {
      if (t.path[1] === "status") {
        statusObj[t.path[2]] = val(t) as string;
      }
    }

    // Build spacing
    const spacingObj: Record<string, number> = {};
    for (const t of spacingTokens) {
      const key = t.path.slice(1).join("-");
      spacingObj[key] = pxToNum(val(t));
    }

    // Build radius
    const radiusObj: Record<string, number> = {};
    for (const t of radiusTokens) {
      const key = t.path[1];
      radiusObj[key] = pxToNum(val(t));
    }

    // Build font sizes
    const fontSizeObj: Record<string, number> = {};
    for (const t of fontSizeTokens) {
      fontSizeObj[t.path[2]] = pxToNum(val(t));
    }

    // Build line heights
    const lineHeightObj: Record<string, number> = {};
    for (const t of lineHeightTokens) {
      lineHeightObj[t.path[2]] = pxToNum(val(t));
    }

    // Build font weights
    const fontWeightObj: Record<string, number> = {};
    for (const t of fontWeightTokens) {
      const v = val(t);
      fontWeightObj[t.path[2]] = typeof v === "number" ? v : parseInt(String(v), 10);
    }

    // Build font families
    const fontFamilyObj: Record<string, string> = {};
    for (const t of fontFamilyTokens) {
      fontFamilyObj[t.path[2]] = val(t) as string;
    }

    // Build typography presets from composite DTCG tokens
    const typographyPresets: Record<string, { fontSize: number; lineHeight: number; fontWeight: number }> = {};
    const presetTokens = dictionary.allTokens.filter(
      (t) => t.path[0] === "font" && t.path[1] === "presets"
    );
    for (const t of presetTokens) {
      const v = val(t);
      if (v && typeof v === "object") {
        const obj = v as Record<string, unknown>;
        typographyPresets[t.path[2]] = {
          fontSize: pxToNum(String(obj.fontSize)),
          lineHeight: pxToNum(String(obj.lineHeight)),
          fontWeight: typeof obj.fontWeight === "number" ? obj.fontWeight : parseInt(String(obj.fontWeight), 10),
        };
      }
    }

    return `/**
 * Native tokens — generated by Style Dictionary from DTCG tokens.
 * Do not edit by hand. Run: pnpm build:tokens
 *
 * All values are concrete (hex colors, px numbers). No CSS vars, no rem.
 */

export const nativeColors = {
  neutral: ${JSON.stringify(neutralObj, null, 4).replace(/\n/g, "\n  ")},
  semantic: ${JSON.stringify(semanticObj, null, 4).replace(/\n/g, "\n  ")},
  status: ${JSON.stringify(statusObj, null, 4).replace(/\n/g, "\n  ")},
} as const;

export const nativeSpacing = ${JSON.stringify(spacingObj, null, 2)} as const;

export const nativeRadius = ${JSON.stringify(radiusObj, null, 2)} as const;

export const nativeFontSize = ${JSON.stringify(fontSizeObj, null, 2)} as const;

export const nativeLineHeight = ${JSON.stringify(lineHeightObj, null, 2)} as const;

export const nativeFontWeight = ${JSON.stringify(fontWeightObj, null, 2)} as const;

export const nativeFontFamily = ${JSON.stringify(fontFamilyObj, null, 2)} as const;

export const nativeTypography = ${JSON.stringify(typographyPresets, null, 2)} as const;
`;
  },
};

// ---------------------------------------------------------------------------
// Custom format: Native theme tokens (light/dark concrete hex maps)
//
// The DTCG theme files (themes/light.json, themes/dark.json) define the SAME
// token paths with different values, so they cannot be merged into a single
// Style Dictionary dictionary. Their values are reference-free concrete hex,
// so this format reads both files directly and flattens each into a concrete
// `{ camelCaseName: hex }` map — emitting `nativeThemeLight` + `nativeThemeDark`
// so React Native code (providers/native.ts) consumes the DTCG themes instead
// of re-hardcoding the palette. Regenerated by `pnpm build:tokens`, exactly
// like src/tokens/native.ts.
// ---------------------------------------------------------------------------

function camelCaseKey(key: string): string {
  return key.replace(/-([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** Flatten a DTCG `theme` node into a concrete `{ camelCaseName: hex }` map. */
function flattenThemeColors(
  themeNode: Record<string, unknown>
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, node] of Object.entries(themeNode)) {
    if (!node || typeof node !== "object") continue;
    const rec = node as Record<string, unknown>;
    if (typeof rec.$value === "string") {
      out[camelCaseKey(key)] = rec.$value;
      continue;
    }
    // Nested group (e.g. `sidebar`) — flatten one level with a prefix.
    for (const [subKey, subNode] of Object.entries(rec)) {
      if (
        subNode &&
        typeof subNode === "object" &&
        typeof (subNode as Record<string, unknown>).$value === "string"
      ) {
        out[camelCaseKey(`${key}-${subKey}`)] = (
          subNode as Record<string, unknown>
        ).$value as string;
      }
    }
  }
  return out;
}

function readNativeTheme(themeFile: string): Record<string, string> {
  const raw = readFileSync(
    join(__dirname, "tokens", "dtcg", "themes", themeFile),
    "utf8"
  );
  const parsed = JSON.parse(raw) as { theme?: Record<string, unknown> };
  if (!parsed.theme) {
    throw new Error(
      `[style-dictionary] ${themeFile} has no top-level "theme" object.`
    );
  }
  return flattenThemeColors(parsed.theme);
}

const nativeThemeTsFormat = {
  name: "ts/native-theme-tokens",
  format: async () => {
    const light = readNativeTheme("light.json");
    const dark = readNativeTheme("dark.json");
    return `/**
 * Native theme tokens — generated by Style Dictionary from DTCG themes
 * (tokens/dtcg/themes/{light,dark}.json). Do not edit by hand.
 * Run: pnpm build:tokens
 *
 * Concrete hex maps for React Native (no CSS vars, no rem). Consumed by
 * providers/native.ts so the native theme mirrors the DTCG themes rather
 * than re-hardcoding the palette.
 */

export const nativeThemeLight = ${JSON.stringify(light, null, 2)} as const;

export const nativeThemeDark = ${JSON.stringify(dark, null, 2)} as const;
`;
  },
};

// ---------------------------------------------------------------------------
// Build function
// ---------------------------------------------------------------------------

async function build() {
  const tokensDir = join(__dirname, "tokens", "dtcg");

  // Build target selector (CLI arg): "all" (default) | "native" | "css".
  //
  // The two outputs land in different places and have opposite ordering needs
  // vs the package's `tsup` bundle (which has `clean: true`, wiping dist/):
  //   - native  → src/tokens/*.ts  MUST be generated BEFORE tsup so the bundled
  //               dist reflects the current DTCG values (not one build behind).
  //   - css     → dist/themes/*.css MUST be generated AFTER tsup's clean, or it
  //               gets wiped.
  // So package.json's build script runs `build:tokens:native && tsup &&
  // build:tokens:css`. The bare "all" target stays available for standalone /
  // manual regeneration.
  const target = process.argv[2] ?? "all";
  const doNative = target === "all" || target === "native";
  const doCss = target === "all" || target === "css";
  if (!doNative && !doCss) {
    throw new Error(
      `[style-dictionary] Unknown build target "${target}". Use one of: all | native | css.`
    );
  }

  // Register all custom formats
  for (const brand of brands) {
    const fmt = shadcnCssFormat(brand);
    StyleDictionary.registerFormat({
      name: fmt.name,
      format: fmt.format,
    });
  }

  StyleDictionary.registerFormat({
    name: nativeTsFormat.name,
    format: nativeTsFormat.format,
  });

  StyleDictionary.registerFormat({
    name: nativeThemeTsFormat.name,
    format: nativeThemeTsFormat.format,
  });

  // Build one CSS file per brand (→ dist/themes/; run AFTER tsup clean).
  if (doCss) {
    for (const brand of brands) {
      const sd = new StyleDictionary({
        source: [
          join(tokensDir, "colors.json"),
          join(tokensDir, "spacing.json"),
          join(tokensDir, "typography.json"),
          join(tokensDir, "themes", "light.json"),
          join(tokensDir, "brands", `${brand.name}.json`),
        ],
        platforms: {
          css: {
            transformGroup: "css",
            buildPath: join(__dirname, "dist", "themes") + "/",
            files: [
              {
                destination: `${brand.name}.css`,
                format: `css/shadcn-${brand.name}`,
              },
            ],
          },
        },
      });

      await sd.buildAllPlatforms();
      console.log(`  wrote dist/themes/${brand.name}.css`);
    }
  }

  // Native token generation (→ src/tokens/; run BEFORE tsup bundles).
  if (doNative) {
  // Build native tokens (brand-agnostic base tokens)
  const sdNative = new StyleDictionary({
    source: [
      join(tokensDir, "colors.json"),
      join(tokensDir, "spacing.json"),
      join(tokensDir, "typography.json"),
    ],
    platforms: {
      native: {
        transforms: ["attribute/cti", "name/kebab"],
        buildPath: join(__dirname, "src", "tokens") + "/",
        files: [
          {
            destination: "native.ts",
            format: "ts/native-tokens",
          },
        ],
      },
    },
  });

  await sdNative.buildAllPlatforms();
  console.log("  wrote src/tokens/native.ts");

  // Build native theme tokens (light/dark concrete hex maps from DTCG themes).
  // The format reads both theme files directly (see nativeThemeTsFormat above),
  // so the single source here just satisfies Style Dictionary's requirement.
  const sdNativeTheme = new StyleDictionary({
    source: [join(tokensDir, "themes", "light.json")],
    platforms: {
      nativeTheme: {
        transforms: ["attribute/cti", "name/kebab"],
        buildPath: join(__dirname, "src", "tokens") + "/",
        files: [
          {
            destination: "native-themes.ts",
            format: "ts/native-theme-tokens",
          },
        ],
      },
    },
  });

  await sdNativeTheme.buildAllPlatforms();
  console.log("  wrote src/tokens/native-themes.ts");
  }

  const built = [
    doCss ? `${brands.length} CSS theme(s)` : null,
    doNative ? "native tokens + native themes" : null,
  ]
    .filter(Boolean)
    .join(" + ");
  console.log(`\nDone — generated ${built}.`);
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
