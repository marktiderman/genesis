// ---------------------------------------------------------------------------
// Helpers: hex -> HSL component string (Shadcn format: "160 84% 39%")
// ---------------------------------------------------------------------------

function hexToHslComponents(hex: string): string {
  if (!/^#[0-9a-fA-F]{6}$/.test(hex)) {
    throw new Error(`[style-dictionary] Expected 6-digit hex color, got: "${hex}". Check your DTCG token files.`);
  }
  const r = parseInt(hex.slice(1, 3), 16) / 255;
  const g = parseInt(hex.slice(3, 5), 16) / 255;
  const b = parseInt(hex.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return `0 0% ${round(l * 100)}%`;
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h = 0;
  if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
  else if (max === g) h = ((b - r) / d + 2) / 6;
  else h = ((r - g) / d + 4) / 6;
  return `${round(h * 360)} ${round(s * 100)}% ${round(l * 100)}%`;
}

function round(n: number): number {
  return Math.round(n * 10) / 10;
}

