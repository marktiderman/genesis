// Write the checked-in contract: `resources.genesis.ts`. Deterministic (tables
// and fields in a fixed order, no timestamps), so a re-run with no schema
// change is byte-for-byte the same file and a review diff shows only what
// changed.

import type { IntrospectedColumn, IntrospectedTable, StorageType } from "./model.js";

const TS_TYPE: Record<StorageType, string> = {
  string: "string",
  number: "number",
  boolean: "boolean",
  // The studio handler sends dates and timestamps as Postgres text, exactly.
  datetime: "string",
  json: "unknown",
};

function quote(value: string): string {
  return JSON.stringify(value);
}

function propKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : quote(name);
}

function typeName(table: IntrospectedTable): string {
  const pascal = `${table.schema}_${table.table}`
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0]!.toUpperCase() + p.slice(1))
    .join("");
  return `${/^[0-9]/.test(pascal) ? "T" : ""}${pascal}Row`;
}

/** The contract's const name for a table, e.g. `publicBrands`. */
function constName(table: IntrospectedTable): string {
  const row = typeName(table).replace(/Row$/, "");
  return row[0]!.toLowerCase() + row.slice(1);
}

function tsType(column: IntrospectedColumn): string {
  const base = column.enumValues?.length ? column.enumValues.map(quote).join(" | ") : TS_TYPE[column.type];
  const element = column.array ? (base.includes("|") ? `(${base})[]` : `${base}[]`) : base;
  return column.nullable ? `${element} | null` : element;
}

function field(column: IntrospectedColumn, indent: string): string {
  const parts: string[] = [`name: ${quote(column.name)}`, `type: ${quote(column.type)}`, `dbType: ${quote(column.dbType)}`];
  if (column.array) parts.push("array: true");
  // Known either way, so a form can tell "may be null" from "can't" (a view's guess is left out).
  if (!column.nullableUnknown) parts.push(column.nullable ? "nullable: true" : "nullable: false");
  if (column.nullable || column.hasDefault || column.generated) parts.push("optional: true");
  if (column.hasDefault) parts.push("hasDefault: true");
  if (column.generated) parts.push("generated: true");
  if (column.enumValues) parts.push(`enumValues: [${column.enumValues.map(quote).join(", ")}]`);
  if (column.references) {
    parts.push(`references: { resource: ${quote(column.references.resource)}, field: ${quote(column.references.field)} }`);
  }
  const label = column.settings?.label;
  const description = column.settings?.description ?? column.description;
  if (label) parts.push(`label: ${quote(label)}`);
  if (description) parts.push(`description: ${quote(description)}`);
  if (column.settings?.widget) parts.push(`widget: ${quote(column.settings.widget)}`);
  if (column.settings?.readonly) parts.push("readOnly: true");
  if (column.settings?.sensitive) parts.push("sensitive: true");
  return `${indent}{ ${parts.join(", ")} },`;
}

export interface EmitOptions {
  /** Where the contract came from, for the header. Never include a secret. */
  source: string;
}

/** Thrown when the contract can't be emitted as asked (a name clash, a labelField that isn't a column). */
export class EmitError extends Error {
  override name = "EmitError";
}

export function emitContracts(tables: readonly IntrospectedTable[], options: EmitOptions): string {
  // Code-point order, not the locale's, so every machine emits the same bytes.
  const sorted = [...tables].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  // Two tables whose names flatten to one identifier (public.a_b and public_a.b) would collide.
  const seen = new Map<string, string>();
  for (const table of sorted) {
    const id = typeName(table);
    const other = seen.get(id);
    if (other) throw new EmitError(`${other} and ${table.name} would both be named ${id}; rename one, or introspect them separately.`);
    seen.set(id, table.name);
    const labelField = table.settings?.labelField;
    if (labelField && !table.columns.some((c) => c.name === labelField)) {
      throw new EmitError(`${table.name}: @genesis labelField "${labelField}" isn't one of its columns.`);
    }
  }
  const out: string[] = [
    "// Generated by `genesis introspect` — do not edit by hand.",
    `// Source: ${options.source}`,
    "//",
    "// Re-run `genesis introspect` after a schema change and review the diff.",
    "// Labels, widgets and descriptions come from `@genesis {...}` settings in",
    "// table and column comments. Pass `contracts` to createStudioHandler: it",
    "// wins over discovery for presentation, while types, keys and every",
    "// permission still come from the live database. Each contract goes through",
    "// defineResource, so a bad @genesis setting fails to compile and views read the",
    "// row type with RowOf<typeof contract>.",
    "",
    'import { defineResource } from "@marktiderman/genesis-core";',
    "",
  ];
  for (const table of sorted) {
    const row = typeName(table);
    out.push(`/** \`${table.name}\`. */`);
    out.push(`export const ${constName(table)} = defineResource<${row}>()({`);
    out.push(`  name: ${quote(table.name)},`);
    out.push(`  key: ${table.key.length === 1 ? quote(table.key[0]!) : `[${table.key.map(quote).join(", ")}]`},`);
    if (table.settings?.label) out.push(`  label: ${quote(table.settings.label)},`);
    if (table.settings?.labelField) out.push(`  labelField: ${quote(table.settings.labelField)},`);
    if (table.settings?.noun) out.push(`  noun: ${quote(table.settings.noun)},`);
    if (table.settings?.nounPlural) out.push(`  nounPlural: ${quote(table.settings.nounPlural)},`);
    const description = table.settings?.description ?? table.description;
    if (description) out.push(`  description: ${quote(description)},`);
    out.push("  fields: [");
    for (const column of table.columns) out.push(field(column, "    "));
    out.push("  ],");
    out.push("});", "");
  }
  out.push("export const contracts = {");
  for (const table of sorted) out.push(`  ${quote(table.name)}: ${constName(table)},`);
  out.push("} as const;", "");
  out.push("/** Every resource in this contract, `schema.table`. */");
  out.push("export type GenesisResource = keyof typeof contracts;", "");
  for (const table of sorted) {
    out.push(`/** A row of \`${table.name}\`, as the studio handler returns it. */`);
    // A type, not an interface: only a type alias fits core's `DataRow` (an index signature).
    out.push(`export type ${typeName(table)} = {`);
    for (const column of table.columns) out.push(`  ${propKey(column.name)}: ${tsType(column)};`);
    out.push("};", "");
    out.push(`/** The field names of \`${table.name}\`. */`);
    out.push(`export type ${typeName(table).replace(/Row$/, "Field")} = keyof ${typeName(table)};`, "");
  }
  out.push("/** Row types by resource. */");
  out.push("export interface GenesisRows {");
  for (const table of sorted) out.push(`  ${quote(table.name)}: ${typeName(table)};`);
  out.push("}", "");
  return out.join("\n");
}
