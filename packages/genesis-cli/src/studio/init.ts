// `genesis studio init`: turn the Data Studio on in an existing app.
//
// Pure planning (what to write, and what to tell the user) is separate from
// the filesystem, so it can be tested on a fake project.

import { studioSetupSql } from "@marktiderman/genesis-studio-server";
import { wireStudioRoute } from "./wire-route.js";

export type StudioHost = "next" | "tanstack-start" | "supabase-function";

export interface ProjectFacts {
  /** The app's package.json, parsed. */
  packageJson: { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
  /** Paths (relative, forward slashes) that exist, among those the planner asks about. */
  exists: (path: string) => boolean;
  /** A file's text, when it exists. */
  read: (path: string) => string | null;
  /** UTC timestamp for the migration file name, `YYYYMMDDHHMMSS`. */
  timestamp: string;
  /** Entries in a folder (optional; used to find a Next.js route group). */
  list?: (path: string) => string[];
  /** Every file under a folder, as relative paths (optional; used to find a TanStack layout route). */
  listDeep?: (path: string) => string[];
}

export interface InitOptions {
  /** Force a host instead of detecting one. */
  host?: StudioHost;
  /** The page's path in the app. Default `/admin/data`. */
  route?: string;
  /** The studio's database login. Default `genesis_studio_login`. */
  loginRole?: string;
}

export interface PlannedFile {
  path: string;
  content: string;
  /** Append to an existing file instead of creating one (config.toml). */
  append?: boolean;
  /** An edit to one of the app's own files (its router): always written, and listed as changed. */
  edit?: string;
}

export interface InitPlan {
  host: StudioHost;
  files: PlannedFile[];
  /** Packages to install in the app. */
  install: string[];
  /** What the user still has to do, in order. */
  steps: string[];
}

const PACKAGES = [
  "@marktiderman/genesis-studio",
  "@marktiderman/genesis-studio-server",
  "@marktiderman/genesis-ui",
  "@marktiderman/genesis-core",
  // Pinned to the ranges the studio supports: an unpinned "latest" can move
  // past them (@hookform/resolvers 6 is a different major).
  "@tanstack/react-query@^5",
  "@tanstack/react-virtual@^3.14",
  "react-hook-form@^7",
  "zod@^4",
  "@hookform/resolvers@^5.1.0",
];

const ROLE = /^[a-z_][a-z0-9_]{0,62}$/;

function has(facts: ProjectFacts, name: string): boolean {
  return Boolean(facts.packageJson.dependencies?.[name] ?? facts.packageJson.devDependencies?.[name]);
}

export function detectHost(facts: ProjectFacts): StudioHost {
  if (has(facts, "next") && (facts.exists("app") || facts.exists("src/app"))) return "next";
  if (has(facts, "@tanstack/react-start") && facts.exists("src/routes")) return "tanstack-start";
  return "supabase-function";
}

/** Lovable and many Vite apps keep one client at this path. */
const LOVABLE_CLIENT = "src/integrations/supabase/client.ts";

export function planStudioInit(facts: ProjectFacts, options: InitOptions = {}): InitPlan {
  const host = options.host ?? detectHost(facts);
  const route = (options.route ?? "/admin/data").replace(/\/+$/, "") || "/admin/data";
  const role = options.loginRole ?? "genesis_studio_login";
  if (!ROLE.test(role)) throw new Error(`"${role}" isn't a plain Postgres role name.`);
  if (!/^\/[A-Za-z0-9/_-]*$/.test(route)) throw new Error(`"${route}" isn't a simple path like /admin/data.`);

  const files: PlannedFile[] = [];
  const steps: string[] = [];
  const supabaseDir = facts.exists("supabase");
  const migrationPath = supabaseDir ? `supabase/migrations/${facts.timestamp}_genesis_studio.sql` : "genesis-studio.sql";

  files.push({
    path: migrationPath,
    content: [
      "-- Genesis Data Studio: its own database login, and the audit trail every edit is written to.",
      "-- Generated by `genesis studio init`. Review it, then apply it like any migration. Safe to run again.",
      "--",
      `-- ${role} can do nothing on its own (NOINHERIT): the studio switches it to the signed-in user's`,
      "-- role for each request, so row-level security applies to everything it shows or saves.",
      "-- Its password is set outside this file (see the steps `genesis studio init` printed).",
      "",
      "do $$",
      "begin",
      `  if not exists (select 1 from pg_roles where rolname = '${role}') then`,
      `    create role ${role} login noinherit;`,
      "  end if;",
      "end $$;",
      `grant authenticated to ${role};`,
      "",
      studioSetupSql({ loginRole: role }),
    ].join("\n"),
  });

  const install = [...PACKAGES];
  const pagePath = route.replace(/^\//, "");

  if (host === "next") {
    const base = facts.exists("src/app") ? "src/app" : "app";
    // A route group with its own layout (app/(dashboard)/layout.tsx) is where the app's shell lives.
    const group = (facts.list?.(base) ?? []).filter((d) => /^\(.+\)$/.test(d) && facts.exists(`${base}/${d}/layout.tsx`));
    const appDir = group.length === 1 ? `${base}/${group[0]}` : base;
    const ssr = has(facts, "@supabase/ssr");
    if (!ssr && !has(facts, "@supabase/supabase-js")) install.push("@supabase/supabase-js");
    files.push({
      path: `${appDir}/api/studio/route.ts`,
      content: `// The Data Studio's server: every table, as the signed-in user. Generated by \`genesis studio init\`.
import { supabaseStudio } from "@marktiderman/genesis-studio-server";

export const runtime = "nodejs";

export const POST = supabaseStudio({
  url: process.env.NEXT_PUBLIC_SUPABASE_URL!,
  database: process.env.STUDIO_DATABASE_URL!,
  // Server-side details of anything that goes wrong; users only see a plain message.
  onError: (error) => console.error("[genesis-studio]", error),
  // Who may open the studio. The default is any signed-in user, who sees exactly what row-level
  // security already lets them see. Narrow it to staff with, e.g.:
  // who: (claims) => (claims.app_metadata as { role?: string } | undefined)?.role === "admin",
});
`,
    });
    files.push({
      path: `${appDir}/${pagePath}/page.tsx`,
      content: `"use client";
// The Data Studio page. Generated by \`genesis studio init\`.
import { useMemo } from "react";
import { ${ssr ? "createBrowserClient" : "createClient"} } from "${ssr ? "@supabase/ssr" : "@supabase/supabase-js"}";
import { DataStudio } from "@marktiderman/genesis-studio";
import { createSupabaseStudioProvider } from "@marktiderman/genesis-studio-server/client";
import "@marktiderman/genesis-studio/standalone.css";

export default function DataStudioPage() {
  const provider = useMemo(() => {
    const supabase = ${ssr ? "createBrowserClient" : "createClient"}(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!);
    return createSupabaseStudioProvider(supabase, { url: "/api/studio" });
  }, []);
  // "plain": no frame of its own, so it sits under the app's header and nav like its other pages.
  return <DataStudio provider={provider} title="Data" variant="plain" />;
}
`,
    });
    steps.push(
      `Set the login's password once, in the Supabase SQL editor (never in a migration): alter role ${role} with password '<a long random password>';`,
      `Add STUDIO_DATABASE_URL to .env.local and your host's settings: the session pooler string from Supabase → Connect, with the user changed to ${role}.<project-ref> and that password.`,
      `Apply ${migrationPath}, then open ${route}.`,
    );
  } else if (host === "tanstack-start") {
    planTanstackStart(facts, route, files, steps, role);
  } else {
    const lovable = facts.read(LOVABLE_CLIENT);
    files.push({
      path: "supabase/functions/genesis-studio/index.ts",
      content: `// The Data Studio's server, as a Supabase Edge Function: every table, as the signed-in user.
// Generated by \`genesis studio init\`. It checks each user's token itself (verify_jwt is off, so the
// browser's CORS preflight can reach it).
import { supabaseStudio } from "npm:@marktiderman/genesis-studio-server@^0";

const handler = supabaseStudio({
  url: Deno.env.get("SUPABASE_URL")!,
  database: Deno.env.get("STUDIO_DATABASE_URL")!,
  // The app's origins, comma-separated, e.g. "https://app.example.com,http://localhost:8080".
  allowedOrigins: (Deno.env.get("STUDIO_ALLOWED_ORIGINS") ?? "").split(",").map((o) => o.trim()).filter(Boolean),
  // Server-side details of anything that goes wrong (the function's logs); users only see a plain message.
  onError: (error) => console.error("[genesis-studio]", error),
  // Who may open the studio. The default is any signed-in user, who sees exactly what row-level
  // security already lets them see. Narrow it to staff with, e.g.:
  // who: (claims) => (claims.app_metadata as { role?: string } | undefined)?.role === "admin",
});

Deno.serve((request) => handler(request));
`,
    });
    if (facts.exists("supabase/config.toml")) {
      const config = facts.read("supabase/config.toml") ?? "";
      if (!/\[functions\.genesis-studio\]/.test(config)) {
        files.push({ path: "supabase/config.toml", append: true, content: `\n[functions.genesis-studio]\nverify_jwt = false\n` });
      }
    } else {
      steps.push("Deploy the function with JWT verification off (the studio verifies tokens itself): supabase functions deploy genesis-studio --no-verify-jwt");
    }
    const clientImport = lovable ? `import { supabase } from "@/integrations/supabase/client";` : `import { createClient } from "@supabase/supabase-js";`;
    const clientSetup = lovable
      ? ""
      : `const supabase = createClient(import.meta.env.VITE_SUPABASE_URL, import.meta.env.VITE_SUPABASE_ANON_KEY);\n`;
    if (!lovable && !has(facts, "@supabase/supabase-js")) install.push("@supabase/supabase-js");
    const componentDir = facts.exists("src/pages") ? "src/pages" : "src";
    // The app's router, so the page can go inside its layout (sidebar, header, theme).
    const routerPath = ["src/App.tsx", "src/app.tsx", "src/router.tsx", "src/routes.tsx", "src/main.tsx"].find((p) =>
      /<Routes\b|<Route\b/.test(facts.read(p) ?? ""),
    );
    const wired = routerPath
      ? wireStudioRoute(facts.read(routerPath)!, route, `./${componentDir.replace(/^src\/?/, "") ? `${componentDir.replace(/^src\//, "")}/` : ""}DataStudioPage`)
      : { skipped: `Add <Route path="${route}" element={<DataStudioPage />} /> to your router, inside the layout your other pages use.` };
    const inShell = Boolean(wired.content);
    files.push({
      path: `${componentDir}/DataStudioPage.tsx`,
      content: `// The Data Studio page. Generated by \`genesis studio init\`: add it to your router at ${route}.
import { useMemo } from "react";
import { DataStudio } from "@marktiderman/genesis-studio";
import { createSupabaseStudioProvider } from "@marktiderman/genesis-studio-server/client";
import "@marktiderman/genesis-studio/standalone.css";
${clientImport}

${clientSetup}const STUDIO_URL = \`\${import.meta.env.VITE_SUPABASE_URL}/functions/v1/genesis-studio\`;

export default function DataStudioPage() {
  const provider = useMemo(() => createSupabaseStudioProvider(supabase, { url: STUDIO_URL }), []);
  return <DataStudio provider={provider} title="Data"${inShell ? ` variant="plain"` : ""} />;
}
`,
    });
    if (wired.content) {
      files.push({
        path: routerPath!,
        content: wired.content,
        edit: `added ${route} inside your app's layout${wired.guard ? `, behind <${wired.guard}>` : ""}`,
      });
    } else {
      steps.push(wired.skipped!);
    }
    steps.push(
      `Set the login's password once, in the Supabase SQL editor (never in a migration): alter role ${role} with password '<a long random password>';`,
      `Set the function's secrets: supabase secrets set STUDIO_DATABASE_URL='<session pooler string from Supabase → Connect, user ${role}.<project-ref>>' STUDIO_ALLOWED_ORIGINS='<your app's origins>'`,
      `Apply ${migrationPath}, deploy the function (supabase functions deploy genesis-studio), then open ${route}.`,
    );
  }

  return { host, files, install, steps };
}

/**
 * TanStack Start: the handler is a server route in the app itself (no Edge
 * Function), and the page goes in the folder of the layout route that draws
 * the app's shell, so it gets the app's nav, header and theme.
 */
function planTanstackStart(facts: ProjectFacts, route: string, files: PlannedFile[], steps: string[], role: string) {
  files.push({
    path: "src/routes/api/studio.ts",
    content: `// The Data Studio's server: every table, as the signed-in user. Generated by \`genesis studio init\`.
import { createFileRoute } from "@tanstack/react-router";

let studio: ((request: Request) => Promise<Response>) | undefined;

export const Route = createFileRoute("/api/studio")({
  server: {
    handlers: {
      POST: async ({ request }) => {
        // Loaded here, on the server only, so database code never reaches the browser bundle.
        const { supabaseStudio } = await import("@marktiderman/genesis-studio-server");
        studio ??= supabaseStudio({
          url: process.env.SUPABASE_URL ?? process.env.VITE_SUPABASE_URL!,
          database: process.env.STUDIO_DATABASE_URL!,
          // Server-side details of anything that goes wrong; users only see a plain message.
          onError: (error) => console.error("[genesis-studio]", error),
          // Who may open the studio. The default is any signed-in user, who sees exactly what
          // row-level security already lets them see. Narrow it to staff with, e.g.:
          // who: (claims) => (claims.app_metadata as { role?: string } | undefined)?.role === "admin",
        });
        return studio(request);
      },
    },
  },
});
`,
  });

  // The layout route that draws the shell: a route.tsx that renders one.
  // Prefer the one that renders an app shell, then the outermost layout: a
  // nested layout (a record's tabs, say) isn't where an app-wide page goes.
  const layouts = (facts.listDeep?.("src/routes") ?? [])
    .filter((p) => p.endsWith("/route.tsx"))
    .map((p) => ({ dir: p.slice(0, -"/route.tsx".length), text: facts.read(p) ?? "" }))
    .filter((r) => /AppShell|Layout|Sidebar/.test(r.text) && !/\$/.test(r.dir));
  const rank = (r: { dir: string; text: string }) => (/AppShell/.test(r.text) ? 0 : 1) * 1000 + r.dir.split("/").length;
  const shellDirs = layouts.sort((a, b) => rank(a) - rank(b)).map((r) => r.dir);
  const dir = shellDirs[0] ?? "src/routes";
  // A route file for a leading segment (admin.tsx for /admin/data) would make the
  // page its child, rendered only if it has an <Outlet>. A trailing "_" on that
  // segment (admin_.data.tsx) keeps the page a sibling, still inside the shell.
  const segments = route.replace(/^\//, "").split("/");
  const named = segments.map((segment, i) => {
    const prefix = segments.slice(0, i + 1).join(".");
    const parent = i < segments.length - 1 && (facts.exists(`${dir}/${prefix}.tsx`) || facts.exists(`${dir}/${prefix}/route.tsx`));
    return parent ? `${segment}_` : segment;
  });
  const id = `${dir.replace(/^src\/routes/, "")}/${named.join("/")}`.replace(/\/+/g, "/");
  const file = `${dir}/${named.join(".")}.tsx`;
  const lovable = facts.exists(LOVABLE_CLIENT);
  const tailwind4 = /@import\s+["']tailwindcss/.test(facts.read("src/styles.css") ?? "");
  files.push({
    path: file,
    content: `// The Data Studio page. Generated by \`genesis studio init\`. It sits inside the app's shell, so it
// gets the app's nav, header and theme.
import { useMemo } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { DataStudio } from "@marktiderman/genesis-studio";
import { createSupabaseStudioProvider } from "@marktiderman/genesis-studio-server/client";
${tailwind4 ? "" : 'import "@marktiderman/genesis-studio/standalone.css";\n'}${lovable ? 'import { supabase } from "@/integrations/supabase/client";' : 'import { createClient } from "@supabase/supabase-js";\n\nconst supabase = createClient(import.meta.env.VITE_SUPABASE_URL, import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY);'}

export const Route = createFileRoute("${id}")({
  ssr: false,
  component: DataStudioPage,
});

function DataStudioPage() {
  const provider = useMemo(() => createSupabaseStudioProvider(supabase, { url: "/api/studio" }), []);
  return <DataStudio provider={provider} title="Data" variant="plain" />;
}
`,
  });
  if (tailwind4) {
    const css = facts.read("src/styles.css")!;
    if (!css.includes("genesis-studio/dist")) {
      const line = '@source "../node_modules/@marktiderman/genesis-studio/dist";';
      const at = css.search(/@source[^\n]*genesis-ui[^\n]*\n/);
      const next =
        at >= 0
          ? css.replace(/(@source[^\n]*genesis-ui[^\n]*\n)/, `$1${line}\n`)
          : css.replace(/(@import\s+["']tailwindcss[^\n]*\n)/, `$1${line}\n`);
      files.push({ path: "src/styles.css", content: next, edit: "Tailwind now also scans the studio's classes" });
    }
  }
  steps.push(
    `Add a link to ${route} in your app's navigation (for staff only, if that's who should see it).`,
    `Set the login's password once, in the Supabase SQL editor (never in a migration): alter role ${role} with password '<a long random password>';`,
    `Add STUDIO_DATABASE_URL to the server's environment: the session pooler string from Supabase → Connect, with the user changed to ${role}.<project-ref> and that password.`,
    `Apply the migration, then open ${route}.`,
  );
}
