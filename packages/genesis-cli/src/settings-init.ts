// `genesis settings init`: the in-app Settings screen's server route (config-layer §4).
//
// It writes one file: the route that serves genesis-supabase's createSettingsHandler, for the
// app's framework. The screen itself is `<GenesisSettings>` on the app's platform-admin page; the
// steps say how to mount it. Pure planning, separate from the filesystem, so it is tested on a
// fake project.

export type SettingsHost = "next" | "tanstack-start" | "react-router" | "expo";

export const SETTINGS_HOSTS: readonly SettingsHost[] = ["next", "tanstack-start", "react-router", "expo"];

export interface SettingsInitFacts {
  /** The app's package.json, parsed. */
  packageJson: { name?: string; dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
  /** Whether a path (relative, forward slashes) exists. */
  exists: (path: string) => boolean;
}

export interface SettingsInitOptions {
  host?: SettingsHost;
  /** The endpoint's path. Default `/api/genesis/settings`. */
  route?: string;
  /** The app's name on the screen. Default: package.json's name without a scope. */
  appName?: string;
}

export interface SettingsInitPlan {
  host: SettingsHost;
  route: string;
  file: { path: string; content: string };
  /** Packages to install in the app. */
  install: string[];
  /** What the developer still does, in order. */
  steps: string[];
}

function has(facts: SettingsInitFacts, name: string): boolean {
  return Boolean(facts.packageJson.dependencies?.[name] ?? facts.packageJson.devDependencies?.[name]);
}

/** The app's framework, by its dependencies; null when it is none this command knows. */
export function detectSettingsHost(facts: SettingsInitFacts): SettingsHost | null {
  if (has(facts, "next")) return "next";
  if (has(facts, "@tanstack/react-start")) return "tanstack-start";
  if (has(facts, "@react-router/dev")) return "react-router";
  if (has(facts, "expo-router")) return "expo";
  return null;
}

/** The handler's options, the same on every host but for where the environment comes from. */
function handlerSource(env: { url: string; key: string; read: (name: string) => string }, appName: string): string {
  return `// The Genesis Settings screen's server. Generated by \`genesis settings init\`.
// Every call runs as the signed-in person (their access token), so the database decides who may
// read and change what: platform admins everything, a tenant's admins that tenant's keys, everyone
// else their own. Only the publishable key is needed here, never the service-role key.
import { createSettingsHandler } from "@marktiderman/genesis-supabase/settings/server";

function required(name: string, value: string | undefined): string {
  if (!value) throw new Error(\`\${name} is not set: the Genesis Settings route needs it.\`);
  return value;
}

const handler = createSettingsHandler({
  supabaseUrl: required("${env.url}", ${env.read(env.url)}),
  supabaseKey: required("${env.key}", ${env.read(env.key)}),
  app: { name: ${JSON.stringify(appName)} },
  // Server-side details of anything that goes wrong; people only see a plain message.
  onError: (error) => console.error("[genesis-settings]", error),
});
`;
}

/** Plans the route file for the app's framework. Throws when the host is unknown or the route isn't a plain path. */
export function planSettingsInit(facts: SettingsInitFacts, options: SettingsInitOptions = {}): SettingsInitPlan {
  const host = options.host ?? detectSettingsHost(facts);
  if (!host) throw new Error("No framework this command knows (Next.js, TanStack Start, React Router or Expo Router) is in package.json: pass --host.");
  const route = (options.route ?? "/api/genesis/settings").replace(/\/+$/, "");
  if (!/^\/[a-z0-9][a-z0-9/_-]*$/.test(route) || route.includes("//")) throw new Error(`"${route}" isn't a simple path like /api/genesis/settings.`);
  const appName = options.appName ?? (facts.packageJson.name ?? "app").replace(/^@[^/]+\//, "");
  const segments = route.slice(1);
  const install = has(facts, "@marktiderman/genesis-supabase") ? [] : ["@marktiderman/genesis-supabase"];
  if (!has(facts, "@supabase/supabase-js")) install.push("@supabase/supabase-js");
  const node = (name: string) => `process.env[${JSON.stringify(name)}]`;
  const steps: string[] = [];
  let file: SettingsInitPlan["file"];

  if (host === "next") {
    const base = facts.exists("src/app") ? "src/app" : "app";
    file = {
      path: `${base}/${segments}/route.ts`,
      content: `${handlerSource({ url: "NEXT_PUBLIC_SUPABASE_URL", key: "NEXT_PUBLIC_SUPABASE_ANON_KEY", read: node }, appName)}
export const POST = handler;
`,
    };
  } else if (host === "tanstack-start") {
    file = {
      path: `src/routes/${segments}.ts`,
      content: `${handlerSource({ url: "SUPABASE_URL", key: "SUPABASE_PUBLISHABLE_KEY", read: node }, appName).replace(
        'import { createSettingsHandler } from "@marktiderman/genesis-supabase/settings/server";',
        'import { createFileRoute } from "@tanstack/react-router";\nimport { createSettingsHandler } from "@marktiderman/genesis-supabase/settings/server";',
      )}
export const Route = createFileRoute(${JSON.stringify(route)})({
  server: { handlers: { POST: ({ request }) => handler(request) } },
});
`,
    };
  } else if (host === "react-router") {
    const name = segments.replace(/\//g, ".");
    file = {
      path: `app/routes/${name}.ts`,
      content: `${handlerSource({ url: "SUPABASE_URL", key: "SUPABASE_PUBLISHABLE_KEY", read: node }, appName)}
// A resource route: POST only, no page.
export async function action({ request }: { request: Request }) {
  return handler(request);
}
`,
    };
    if (!facts.exists("app/routes.ts") || has(facts, "@react-router/fs-routes")) {
      steps.push(`With file-system routes, ${file.path} is ${route} already.`);
    } else {
      steps.push(`Add the route to app/routes.ts: route(${JSON.stringify(segments)}, ${JSON.stringify(`routes/${name}.ts`)}). React Router needs a server build (ssr: true) to answer it.`);
    }
  } else {
    const base = facts.exists("src/app") ? "src/app" : "app";
    file = {
      path: `${base}/${segments}+api.ts`,
      content: `${handlerSource({ url: "EXPO_PUBLIC_SUPABASE_URL", key: "EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY", read: node }, appName)}
export function POST(request: Request) {
  return handler(request);
}
`,
    };
    steps.push('Expo Router serves API routes from a server build: set web.output to "server" in the app config, and deploy the server (EAS Hosting, or any host for `expo export`).');
  }

  steps.push(
    "Add genesis-supabase's settings-host block (genesis add settings-host; it needs the settings block) and apply its migration, then write the manifest on every deploy (genesis settings sync): the screen's catalogue comes from it.",
    `Mount the screen on your platform-admin page: <GenesisSettings client={createSettingsClient(fetch, { baseUrl: "${route}", token: () => session?.access_token ?? null })} capabilities={APP_HOST_CAPABILITIES} /> (genesis-config's settings/react and settings-protocol). For a tenant's admins, pass tenant={theTenantId}.`,
  );
  return { host, route, file, install, steps };
}
